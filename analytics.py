"""Pure analytics helpers for the FODS retail dashboard.

Input: cleaned sales lines generated by scripts/prepare_data.py.
No Streamlit imports, so model logic can be tested independently and reused in Colab.
"""
from __future__ import annotations
from dataclasses import dataclass
import numpy as np
import pandas as pd
from sklearn.cluster import KMeans
from sklearn.preprocessing import StandardScaler
from sklearn.linear_model import LinearRegression
from sklearn.metrics import mean_absolute_error, mean_squared_error, r2_score

# Known codes used for postage, administrative adjustments or service charges.
# Excluded from *product* rankings/clustering only; they remain in sales-overview totals.
NON_MERCHANDISE_CODES = {
    'POST','DOT','M','BANK CHARGES','AMAZONFEE','S','D','CRUK','C2','B',
    'ADJUST','ADJUST2','PADS',
}


def product_lines(df:pd.DataFrame)->pd.DataFrame:
    return df.loc[~df['stock_code'].str.upper().isin(NON_MERCHANDISE_CODES)]


def product_summary(df:pd.DataFrame)->pd.DataFrame:
    items=product_lines(df)
    if items.empty:
        return pd.DataFrame(columns=['stock_code','description','units','revenue','orders','active_months'])
    df2=items.assign(month=items['date'].dt.to_period('M'))
    result=(df2.groupby('stock_code', as_index=False)
        .agg(description=('description','first'), units=('quantity','sum'),
             revenue=('sales','sum'), orders=('invoice','nunique'),
             active_months=('month','nunique')))
    return result.sort_values('units',ascending=False).reset_index(drop=True)


def kmeans_products(summary:pd.DataFrame, k:int=3)->pd.DataFrame:
    out=summary.copy()
    if len(out)<k:
        out['cluster']='Not available'
        return out
    features=['units','revenue','orders','active_months']
    transformed=np.log1p(out[features].clip(lower=0))
    scaled=StandardScaler().fit_transform(transformed)
    labels=KMeans(n_clusters=k,n_init=10,random_state=42).fit_predict(scaled)
    out['cluster']=['Group '+str(n+1) for n in labels]
    return out


def weekly_history(df:pd.DataFrame, stock_code:str)->pd.DataFrame:
    """Generate complete calendar weeks; excludes incomplete boundary weeks.

    This demo uses all countries by default, regardless of dashboard exploration filters.
    Missing product-week sales are filled with zero recorded units (not imputed purchases).
    """
    if df.empty:
        return pd.DataFrame(columns=['week','units'])
    start=df['date'].min().to_period('W-SUN').start_time + pd.Timedelta(weeks=1)
    end=df['date'].max().to_period('W-SUN').start_time - pd.Timedelta(weeks=1)
    if end<start:
        return pd.DataFrame(columns=['week','units'])
    week_index=pd.date_range(start,end,freq='W-MON')
    subset=df.loc[df['stock_code']==stock_code,['date','quantity']].copy()
    if subset.empty:
        return pd.DataFrame({'week':week_index,'units':np.zeros(len(week_index),dtype=int)})
    subset['week']=subset['date'].dt.to_period('W-SUN').dt.start_time
    grouped=subset.groupby('week')['quantity'].sum().reindex(week_index,fill_value=0)
    return pd.DataFrame({'week':week_index,'units':grouped.to_numpy()})


def eligible_products(df:pd.DataFrame, limit:int=30)->pd.DataFrame:
    """Select consistently sold products instead of rare products with mostly zero weeks."""
    summary=product_summary(df)
    return summary.loc[summary['orders']>=100].sort_values('orders',ascending=False).head(limit)


def lagged_features(y:np.ndarray,t:int)->list[float]:
    return [float(y[t-1]),float(y[t-2]),float(y[t-4]),float(np.mean(y[t-4:t])),float(t)]


def model_result(history:pd.DataFrame, holdout_weeks:int=10)->dict:
    """Transparent one-week-ahead linear regression demo with chronological holdout.

    Evaluation features use only preceding weeks, including actual test-period history
    that would be available at each successive forecast origin. This is rolling
    one-step-ahead *backtesting*, not a multi-step forecast for an unseen year.
    """
    y=history['units'].to_numpy(dtype=float)
    if len(y)<22 or np.count_nonzero(y)<12:
        raise ValueError('Not enough active weeks for a meaningful weekly model.')
    rows=[lagged_features(y,t) for t in range(4,len(y))]
    X=np.asarray(rows,float)
    labels=y[4:]
    if len(X)-holdout_weeks<12:
        raise ValueError('Not enough training weeks for the selected holdout.')
    train_end=len(X)-holdout_weeks
    model=LinearRegression().fit(X[:train_end],labels[:train_end])
    predictions=np.clip(model.predict(X[train_end:]),0,None)
    observed=labels[train_end:]
    baseline=np.asarray([np.mean(y[t-4:t]) for t in range(4+train_end,len(y))])
    metrics={
        'MAE':float(mean_absolute_error(observed,predictions)),
        'RMSE':float(np.sqrt(mean_squared_error(observed,predictions))),
        'R2':float(r2_score(observed,predictions)),
        'Baseline MAE':float(mean_absolute_error(observed,baseline)),
        'Baseline RMSE':float(np.sqrt(mean_squared_error(observed,baseline))),
    }
    frame=pd.DataFrame({'week':history['week'].iloc[4+train_end:].to_numpy(),
                        'actual':observed,'linear_regression':predictions,
                        'historical_average_baseline':baseline})
    all_model=LinearRegression().fit(X,labels)
    next_week=history['week'].iloc[-1]+pd.Timedelta(weeks=1)
    estimate=float(np.clip(all_model.predict([lagged_features(y,len(y))])[0],0,None))
    return {'metrics':metrics,'holdout':frame,'next_week':next_week,
            'estimate':estimate,'weeks_training':train_end,
            'weeks_testing':holdout_weeks,'history':history}
